/* ---------------------------------------------------------------------------
   Two artifacts from one source tree.

   The package is ESM and imports its vendor libraries by name, which is what an
   Astro app wants. But markdownwizard is also a double-clickable offline app —
   the README promises it, analytics deliberately skips file://, and the e2e
   suite has a section devoted to it — and ES modules cannot load from file://
   at all: the browser blocks them as cross-origin from a null origin.

   So the IIFE build exists to keep that promise. It bundles ONLY this package's
   own code and resolves the vendor imports to the globals the offline page has
   already loaded via <script src>, rather than inlining a second copy of marked,
   DOMPurify, docx and pdfmake.

   The vendor shims are GENERATED from what src/ actually imports rather than
   hand-listed. A hand-written list is a second place to remember, and it broke
   on the first build: docx alone needs fifteen named members and the first
   attempt missed two of them.
--------------------------------------------------------------------------- */
import { build } from 'esbuild';
import { mkdir, writeFile, readFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const shimDir = join(here, '.shims');

// Which global each bare import is served by in the offline page.
const VENDOR_GLOBALS = {
  marked: 'marked',
  dompurify: 'DOMPurify',
  docx: 'docx',
  pdfmake: 'pdfMake',
};

async function jsFiles(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await jsFiles(p)));
    else if (e.name.endsWith('.js')) out.push(p);
  }
  return out;
}

// Collect every named and default import taken from each vendor across the source tree.
const named = Object.fromEntries(Object.keys(VENDOR_GLOBALS).map((v) => [v, new Set()]));
const wantsDefault = new Set();

for (const file of await jsFiles(join(root, 'src'))) {
  const src = await readFile(file, 'utf8');
  for (const vendor of Object.keys(VENDOR_GLOBALS)) {
    const re = new RegExp(`import\\s+([^;]+?)\\s+from\\s+'${vendor}'`, 'g');
    for (const m of src.matchAll(re)) {
      const clause = m[1].trim();
      const braces = clause.match(/\{([^}]*)\}/);
      if (braces) {
        for (const n of braces[1].split(',')) {
          const name = n.trim().split(/\s+as\s+/)[0].trim();
          if (name) named[vendor].add(name);
        }
      }
      if (/^[A-Za-z_$][\w$]*/.test(clause.replace(/\{[^}]*\}/, '').replace(/^,|,$/, '').trim())) {
        wantsDefault.add(vendor);
      }
    }
  }
}

await mkdir(shimDir, { recursive: true });
const alias = {};
for (const [vendor, global] of Object.entries(VENDOR_GLOBALS)) {
  const names = [...named[vendor]].sort();
  const lines = [
    `// Generated by build/build.mjs — do not edit.`,
    `// Resolves the bare '${vendor}' import to the global the offline page already loaded.`,
    `const lib = globalThis.${global};`,
    ...names.map((n) => `export const ${n} = lib?.${n} ?? lib;`),
    `export default lib;`,
  ];
  const file = join(shimDir, `${vendor}.js`);
  await writeFile(file, lines.join('\n') + '\n');
  alias[vendor] = file;
  console.log(`  shim ${vendor.padEnd(10)} -> globalThis.${global}${names.length ? `  (${names.length} named)` : ''}`);
}

// The offline page loads vfs_fonts.js as a <script> that self-registers against
// the pdfMake global. Do not bundle the ~768 KB of Roboto into the IIFE, and do
// not require pdfmake to be installed at build time (it is a peer).
const vfsStub = join(shimDir, 'pdfmake-vfs_fonts.js');
await writeFile(
  vfsStub,
  [
    `// Generated by build/build.mjs — do not edit.`,
    `// Offline page already registered fonts via <script src="vfs_fonts.js">.`,
    `export default {};`,
    ``,
  ].join('\n'),
);
alias['pdfmake/build/vfs_fonts.js'] = vfsStub;
console.log('  shim pdfmake/build/vfs_fonts.js -> empty stub (script-tag VFS)');

await build({
  entryPoints: [join(root, 'src', 'index.js')],
  outfile: join(root, 'dist', 'markdownwizard-tools.iife.js'),
  bundle: true,
  format: 'iife',
  globalName: 'MDWTools',
  target: ['es2019'],
  // Not minified on purpose: this ships to a page whose whole pitch is that you can read what it
  // does, and the saving is irrelevant beside the vendor bundles already on the page.
  minify: false,
  alias,
});

console.log('built dist/markdownwizard-tools.iife.js (vendors resolved to globals)');
